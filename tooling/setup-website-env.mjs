import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const websiteDir = join(root, "Website");
const envLocalPath = join(websiteDir, ".env.local");
const devVarsPath = join(websiteDir, ".dev.vars");

function readEnv(path) {
  if (!existsSync(path)) return {};
  return parseEnv(readFileSync(path, "utf8"));
}

function quoteEnvValue(value) {
  if (value == null) return "";
  const text = String(value);
  if (!text || /[\s#"']/u.test(text)) return JSON.stringify(text);
  return text;
}

function randomSecret() {
  return randomBytes(32).toString("hex");
}

const fromEnvLocal = readEnv(envLocalPath);
const fromDevVars = readEnv(devVarsPath);
const next = {
  ...fromEnvLocal,
  ...fromDevVars,
};

if (!String(next.GOOGLE_SHEET_URL || "").trim()) {
  next.GOOGLE_SHEET_URL = next.googleSheetsURL || next.googleSheetUrl || "";
}

const generated = [];
for (const key of ["WEBSITE_ADMIN_KEY", "WEBSITE_FORM_KEY"]) {
  if (String(next[key] || "").trim().length < 32) {
    next[key] = randomSecret();
    generated.push(key);
  }
}

const preferredOrder = [
  "GOOGLE_SHEET_URL",
  "WEBSITE_ADMIN_KEY",
  "WEBSITE_FORM_KEY",
  "RECAPTCHA_SITE_KEY",
  "RECAPTCHA_SECRET_KEY",
  "BREVO_API_KEY",
  "ADMIN_ALLOWED_ORIGINS",
];

const keys = [
  ...preferredOrder,
  ...Object.keys(next).filter((key) => !preferredOrder.includes(key)).sort(),
].filter((key, index, list) => list.indexOf(key) === index);

const body = [
  "# Local Website worker variables. This file is ignored by git.",
  "# Generated by npm run setup:website.",
  ...keys.map((key) => `${key}=${quoteEnvValue(next[key])}`),
  "",
].join("\n");

writeFileSync(devVarsPath, body, "utf8");

const configured = keys.filter((key) => String(next[key] || "").trim());
const missing = keys.filter((key) => !String(next[key] || "").trim());

console.log(`Wrote Website/.dev.vars with ${configured.length} configured keys.`);
if (generated.length) console.log(`Generated local secrets: ${generated.join(", ")}.`);
if (missing.length) console.log(`Still empty: ${missing.join(", ")}.`);
console.log("Restart the Website dev server after changing .dev.vars.");
